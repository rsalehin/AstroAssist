"""Artifact fixtures shared by backend tests and the frontend [F-EVAL-001].

``astroassist eval fixtures --ts`` writes a TypeScript module of example artifacts generated
from the Python models, so UI component tests render exactly the shapes the backend emits.
"""

from __future__ import annotations

import json
from pathlib import Path

import astropy.units as u
from astropy.coordinates import SkyCoord

from astroassist.core.artifacts import (
    Artifact,
    QueryArtifact,
    ResolvedObject,
    ScientificValue,
    Uncertainty,
    artifact_to_dict,
)
from astroassist.core.provenance import Provenance
from astroassist.core.units import QuantityValue, SkyCoordValue

DEFAULT_TS_PATH = Path("frontend/src/test/fixtures/artifacts.ts")


def example_artifacts() -> dict[str, Artifact]:
    """Representative artifacts, one per card the M0/M1 UI renders."""
    return {
        "echoValue": ScientificValue(
            summary="Echo complete — 5 characters echoed",
            provenance=Provenance(method="derived", source="astroassist", tool="echo@1"),
            value=QuantityValue(value=5.0, unit=""),
        ),
        "scientificValue": ScientificValue(
            summary="distance = 4.965 ± 0.010 pc",
            provenance=Provenance(method="derived", source="Gaia DR3"),
            value=QuantityValue.from_quantity(4.965 * u.pc),
            uncertainty=Uncertainty(symmetric=QuantityValue.from_quantity(0.01 * u.pc)),
        ),
        "resolvedObject": ResolvedObject(
            summary="AD Leo (M3.5Ve flare star)",
            provenance=Provenance(method="resolver", source="SIMBAD"),
            canonical_name="AD Leo",
            aliases=["GJ 388", "V* AD Leo"],
            coordinate=SkyCoordValue.from_skycoord(
                SkyCoord(ra=154.9017 * u.deg, dec=19.8699 * u.deg)
            ),
            object_type="Flare Star",
            spectral_type="M3.5Ve",
            resolver="SIMBAD",
        ),
        "query": QueryArtifact(
            summary="SIMBAD resolve 'AD Leo'",
            provenance=Provenance(method="resolver", source="SIMBAD"),
            source="SIMBAD",
            protocol="astroquery",
            query_text="Simbad.query_object('AD Leo')",
            status="ok",
            row_count=1,
            runtime_ms=243,
        ),
    }


def _render_ts(artifacts: dict[str, Artifact]) -> str:
    lines = [
        "// AUTO-GENERATED by `astroassist eval fixtures --ts`. Do not edit by hand.",
        "// Regenerate after changing artifact models so UI and backend stay in sync.",
        "",
    ]
    names = list(artifacts)
    for name in names:
        payload = json.dumps(artifact_to_dict(artifacts[name]), indent=2)
        lines.append(f"export const {name} = {payload};")
        lines.append("")
    joined = ", ".join(names)
    lines.append(f"export const artifactFixtures = {{ {joined} }};")
    lines.append("")
    return "\n".join(lines)


def write_ts_fixtures(out: Path | None = None) -> Path:
    out_path = Path(out) if out is not None else DEFAULT_TS_PATH
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(_render_ts(example_artifacts()), encoding="utf-8")
    return out_path
